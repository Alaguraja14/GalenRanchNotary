                        <li>(first and last page) [submit a notarized copy if sent by mail]</li>
                    </ul>

                    <p class="md:text-xl text-base font-semibold mt-4">3. Proof of your US Visa Status</p>

                    <ul class="list-decimal py-4 md:px-10 px-4 space-y-3 md:text-base text-sm leading-relaxed">
                        <li>[any one of the following; submit a notarized copy if sent by mail; Not applicable for US
                            citizen]</li>
                        <li>Photocopy of the page containing visa on passport (H1B, H4 etc.) and the copy of I-94</li>
                        <li>Clear Photocopy of Green Card</li>
                        <li>Employment Authorization Document (Work Permit)</li>
                        <li>I-797, I-140 or I-20 (If approval copy of these notices is pending, attach a handwritten
                            note detailing the efforts being taken to regularize status)</li>
                    </ul>

                    <p class="md:text-xl text-base font-semibold mt-4">4. Proof of current US residence address </p>

                    <ul class="list-decimal py-4 md:px-10 px-4 space-y-3 md:text-base text-sm leading-relaxed">
                        <li>[any one of the following; submit a notarized copy if sent by mail]:</li>
                        <li>U.S Driving license.</li>
                        <li>PG&E, Water or landline telephone bill displaying applicant’s address</li>
                        <li>House Lease Agreement</li>
                        <li>State Identification Card</li>
                        <li>State Identification Card</li>
                        <li>Note: Bank/credit card/mobile phone statements are not accepted as residence proof</li>
                    </ul>

                    <p class="md:text-xl text-base font-semibold mt-4">5. Power of Attorney needs to be signed and
                        witnessed by two individuals </p>

                    <ul class="list-disc py-4 md:px-10 px-4 space-y-3 md:text-base text-sm leading-relaxed">
                        <li> (other than immediate family members) with their names and addresses clearly mentioned. It
                            has to be duly notarized and further apostilled before submitting to the Consulate for
                            attestation. Apostilling is done at the offices of the Secretary of State where the
                            applicant is resident. For details, please check the state government’s websites. For
                            example, residents of California may check the website <a href="https://www.sos.ca.gov/"
                                target="_blank" class='text-blue-500 underline'>sos.ca.gov.</a> (to be submitted in two
                            sets – original for attestation and one photocopy for office record).</li>

                    </ul>

                    <p class="md:text-xl text-base font-semibold mt-4">6. Witnesses’ signatures </p>

                    <ul class="list-disc py-4 md:px-10 px-4 space-y-3 md:text-base text-sm leading-relaxed">
                        <li> Have to be duly notarized. Also submit duly notarized copy of a valid ID proof of each
                            Witness. Mention Witness 1 and Witness 2 on top of each ID proof.</li>
                    </ul>

